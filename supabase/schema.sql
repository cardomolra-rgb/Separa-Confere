-- Separa & Confere — esquema do banco (Supabase / Postgres)
-- Já aplicado no projeto. Guardado aqui como registro e para recriar o banco se precisar.
-- Tabelas com prefixo sc_. Acesso somente via funções (RPC) com token de sessão; as tabelas
-- têm RLS ligado e nenhuma política, então a chave pública não lê nem grava nelas diretamente.

create table public.sc_operadores (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  papel text not null check (papel in ('separacao','conferencia','gerente')),
  pin_hash text not null,
  ativo boolean not null default true,
  tentativas int not null default 0,
  bloqueado_ate timestamptz,
  criado timestamptz not null default now()
);
create unique index sc_operadores_nome_uq on public.sc_operadores (lower(nome));

create table public.sc_sessoes (
  token uuid primary key default gen_random_uuid(),
  operador_id uuid not null references public.sc_operadores(id) on delete cascade,
  criado timestamptz not null default now(),
  expira timestamptz not null default now() + interval '30 days'
);
create index sc_sessoes_operador_idx on public.sc_sessoes(operador_id);

create table public.sc_pedidos (
  id bigint generated by default as identity (start with 1001) primary key,
  status text not null default 'aguardando' check (status in ('aguardando','separando','conferir','divergente','concluido')),
  doc jsonb not null,
  versao int not null default 1,
  criado_por uuid references public.sc_operadores(id) on delete set null,
  criado timestamptz not null default now(),
  atualizado timestamptz not null default now()
);
create index sc_pedidos_status_idx on public.sc_pedidos(status, atualizado desc);

alter table public.sc_operadores enable row level security;
alter table public.sc_sessoes enable row level security;
alter table public.sc_pedidos enable row level security;
revoke all on public.sc_operadores, public.sc_sessoes, public.sc_pedidos from anon, authenticated;

-- sessão -> operador
create or replace function public.sc__operador(p_token uuid)
returns public.sc_operadores language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores;
begin
  select op.* into o from sc_sessoes s join sc_operadores op on op.id = s.operador_id
   where s.token = p_token and s.expira > now() and op.ativo;
  if o.id is null then raise exception 'sessao_invalida' using errcode = 'P0001'; end if;
  return o;
end $$;

create or replace function public.sc__op_json(o public.sc_operadores)
returns jsonb language sql immutable set search_path = public as $$
  select jsonb_build_object('id', o.id, 'nome', o.nome, 'papel', o.papel)
$$;

create or replace function public.sc__pedido_json(p public.sc_pedidos)
returns jsonb language sql stable set search_path = public as $$
  select p.doc || jsonb_build_object('id', p.id::text, 'status', p.status, 'versao', p.versao, 'criado', p.criado, 'atualizado', p.atualizado)
$$;

-- público: estado da instalação e lista de nomes para a tela de entrada
create or replace function public.sc_inicio()
returns jsonb language sql security definer set search_path = public as $$
  select jsonb_build_object(
    'configurado', exists(select 1 from sc_operadores),
    'operadores', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'papel', papel) order by nome)
                             from sc_operadores where ativo), '[]'::jsonb))
$$;

create or replace function public.sc_criar_primeiro_gerente(p_nome text, p_pin text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare o public.sc_operadores; t uuid;
begin
  perform pg_advisory_xact_lock(hashtext('sc_setup'));
  if exists(select 1 from sc_operadores) then raise exception 'ja_configurado'; end if;
  if coalesce(trim(p_nome),'') = '' then raise exception 'nome_obrigatorio'; end if;
  if p_pin !~ '^\d{4}$' then raise exception 'pin_invalido'; end if;
  insert into sc_operadores(nome, papel, pin_hash) values (trim(p_nome), 'gerente', crypt(p_pin, gen_salt('bf')))
  returning * into o;
  insert into sc_sessoes(operador_id) values (o.id) returning token into t;
  return jsonb_build_object('token', t, 'operador', sc__op_json(o));
end $$;

-- entrada por PIN, com bloqueio de 5 minutos após 5 erros
create or replace function public.sc_entrar(p_operador uuid, p_pin text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare o public.sc_operadores; t uuid;
begin
  select * into o from sc_operadores where id = p_operador and ativo for update;
  if o.id is null then raise exception 'operador_nao_encontrado'; end if;
  if o.bloqueado_ate is not null and o.bloqueado_ate > now() then
    return jsonb_build_object('erro', 'bloqueado', 'minutos', ceil(extract(epoch from o.bloqueado_ate - now()) / 60)::int);
  end if;
  if o.pin_hash <> crypt(coalesce(p_pin,''), o.pin_hash) then
    if o.tentativas + 1 >= 5 then
      update sc_operadores set tentativas = 0, bloqueado_ate = now() + interval '5 minutes' where id = o.id;
      return jsonb_build_object('erro', 'bloqueado', 'minutos', 5);
    end if;
    update sc_operadores set tentativas = o.tentativas + 1 where id = o.id;
    return jsonb_build_object('erro', 'pin_incorreto', 'restam', 4 - o.tentativas);
  end if;
  update sc_operadores set tentativas = 0, bloqueado_ate = null where id = o.id;
  delete from sc_sessoes where expira < now();
  insert into sc_sessoes(operador_id) values (o.id) returning token into t;
  return jsonb_build_object('token', t, 'operador', sc__op_json(o));
end $$;

create or replace function public.sc_eu(p_token uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores;
begin
  o := sc__operador(p_token);
  update sc_sessoes set expira = now() + interval '30 days' where token = p_token;
  return sc__op_json(o);
end $$;

create or replace function public.sc_sair(p_token uuid)
returns void language sql security definer set search_path = public as $$
  delete from sc_sessoes where token = p_token
$$;

-- pedidos
create or replace function public.sc_listar_pedidos(p_token uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform sc__operador(p_token);
  return coalesce((select jsonb_agg(sc__pedido_json(p) order by p.id)
                     from sc_pedidos p
                    where p.status <> 'concluido' or p.atualizado > now() - interval '30 days'), '[]'::jsonb);
end $$;

create or replace function public.sc_criar_pedido(p_token uuid, p_doc jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores; p public.sc_pedidos;
begin
  o := sc__operador(p_token);
  if jsonb_typeof(p_doc->'itens') <> 'array' or jsonb_array_length(p_doc->'itens') = 0 then raise exception 'itens_obrigatorios'; end if;
  if coalesce(trim(p_doc->>'cliente'),'') = '' then raise exception 'cliente_obrigatorio'; end if;
  insert into sc_pedidos(status, doc, criado_por)
  values ('aguardando', p_doc - 'id' - 'status' - 'versao' - 'criado' - 'atualizado', o.id)
  returning * into p;
  return sc__pedido_json(p);
end $$;

-- grava com controle de versão (conflito devolve a versão atual) e confere a função de quem grava
create or replace function public.sc_salvar_pedido(p_token uuid, p_id bigint, p_versao int, p_doc jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores; p public.sc_pedidos; novo text;
begin
  o := sc__operador(p_token);
  select * into p from sc_pedidos where id = p_id for update;
  if p.id is null then raise exception 'pedido_nao_encontrado'; end if;
  if p.versao <> p_versao then
    return jsonb_build_object('conflito', true, 'pedido', sc__pedido_json(p));
  end if;
  novo := coalesce(p_doc->>'status', p.status);
  if novo not in ('aguardando','separando','conferir','divergente','concluido') then raise exception 'status_invalido'; end if;
  if o.papel <> 'gerente' then
    if p.status in ('aguardando','separando') and o.papel <> 'separacao' then raise exception 'sem_permissao:separacao'; end if;
    if p.status in ('conferir','divergente') and o.papel <> 'conferencia' then raise exception 'sem_permissao:conferencia'; end if;
    if p.status = 'concluido' then raise exception 'sem_permissao:gerente'; end if;
  end if;
  update sc_pedidos set status = novo,
         doc = p_doc - 'id' - 'status' - 'versao' - 'criado' - 'atualizado',
         versao = versao + 1, atualizado = now()
   where id = p_id returning * into p;
  return jsonb_build_object('pedido', sc__pedido_json(p));
end $$;

create or replace function public.sc_excluir_pedido(p_token uuid, p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores;
begin
  o := sc__operador(p_token);
  if o.papel <> 'gerente' then raise exception 'sem_permissao:gerente'; end if;
  delete from sc_pedidos where id = p_id;
end $$;

-- operadores (gerente)
create or replace function public.sc_operadores_listar(p_token uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores;
begin
  o := sc__operador(p_token);
  if o.papel <> 'gerente' then raise exception 'sem_permissao:gerente'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'papel', papel, 'ativo', ativo) order by ativo desc, nome) from sc_operadores), '[]'::jsonb);
end $$;

create or replace function public.sc_operador_salvar(p_token uuid, p_id uuid, p_nome text, p_papel text, p_pin text, p_ativo boolean)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare o public.sc_operadores; r public.sc_operadores;
begin
  o := sc__operador(p_token);
  if o.papel <> 'gerente' then raise exception 'sem_permissao:gerente'; end if;
  if coalesce(trim(p_nome),'') = '' then raise exception 'nome_obrigatorio'; end if;
  if p_pin is not null and p_pin <> '' and p_pin !~ '^\d{4}$' then raise exception 'pin_invalido'; end if;
  if p_id is null then
    if coalesce(p_pin,'') = '' then raise exception 'pin_obrigatorio'; end if;
    insert into sc_operadores(nome, papel, pin_hash, ativo) values (trim(p_nome), p_papel, crypt(p_pin, gen_salt('bf')), coalesce(p_ativo, true)) returning * into r;
  else
    if p_id = o.id and (p_papel <> 'gerente' or p_ativo = false) then raise exception 'nao_pode_rebaixar_a_si'; end if;
    update sc_operadores set nome = trim(p_nome), papel = p_papel, ativo = coalesce(p_ativo, ativo),
           pin_hash = case when coalesce(p_pin,'') <> '' then crypt(p_pin, gen_salt('bf')) else pin_hash end,
           tentativas = 0, bloqueado_ate = null
     where id = p_id returning * into r;
    if r.id is null then raise exception 'operador_nao_encontrado'; end if;
    if not r.ativo or coalesce(p_pin,'') <> '' then delete from sc_sessoes where operador_id = r.id and token <> p_token; end if;
  end if;
  return jsonb_build_object('id', r.id, 'nome', r.nome, 'papel', r.papel, 'ativo', r.ativo);
exception when unique_violation then raise exception 'nome_repetido';
end $$;

-- gerente exclui operador (não pode excluir a si mesmo)
create or replace function public.sc_operador_excluir(p_token uuid, p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare o public.sc_operadores;
begin
  o := sc__operador(p_token);
  if o.papel <> 'gerente' then raise exception 'sem_permissao:gerente'; end if;
  if p_id = o.id then raise exception 'nao_pode_excluir_a_si'; end if;
  delete from sc_operadores where id = p_id;
  if not found then raise exception 'operador_nao_encontrado'; end if;
end $$;

-- aviso em tempo real para os aparelhos (só o id, sem dados)
create or replace function public.sc__avisar()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform realtime.send(jsonb_build_object('id', coalesce(new.id, old.id), 'op', tg_op), 'mudou', 'sc_pedidos', false);
  return null;
exception when others then return null;
end $$;
create trigger sc_pedidos_avisar after insert or update or delete on public.sc_pedidos
for each row execute function public.sc__avisar();

-- permissões de execução
revoke execute on function public.sc__operador(uuid), public.sc__op_json(public.sc_operadores), public.sc__pedido_json(public.sc_pedidos), public.sc__avisar() from public, anon, authenticated;
grant execute on function
  public.sc_inicio(), public.sc_criar_primeiro_gerente(text,text), public.sc_entrar(uuid,text), public.sc_eu(uuid), public.sc_sair(uuid),
  public.sc_listar_pedidos(uuid), public.sc_criar_pedido(uuid,jsonb), public.sc_salvar_pedido(uuid,bigint,int,jsonb), public.sc_excluir_pedido(uuid,bigint),
  public.sc_operadores_listar(uuid), public.sc_operador_salvar(uuid,uuid,text,text,text,boolean), public.sc_operador_excluir(uuid,uuid)
to anon, authenticated;
